"""SQL (PostgreSQL dialect) language module. One scanner, `_scan`, produces
both the comment list and the normal form, so they can't disagree.

`--` and `/*` are comment markers only outside a literal, and Postgres has
many literal forms that routinely carry them:

  * dollar quoting `$$ ... $$` / `$tag$ ... $tag$` -- opens only at a token
    start (`$` is an identifier char, so `a$$b` is one identifier).
  * `'...'` (``''`` is an embedded quote), `E'...'` (backslash-escaped),
    `"quoted identifiers"` (``""`` doubling, no backslash escapes),
    `B'..' X'..' N'..' U&'..'` (prefix + ordinary `''` string).
  * `COPY ... FROM stdin;` data blocks: every line up to `\\.` is raw table
    data, not SQL, found from the statement (which may wrap across lines) not
    a single line -- missing one silently cuts a `--` out of a data row.
  * psql meta-commands (`\\restrict`, `\\connect`, `\\.`) are not SQL.

Two hyphens comment only when ADJACENT (`a - -1` is 3 tokens, `a--1` is `a`
+ comment), matching Postgres's own lexer.

normal form: one record per token, `<kind> \\t <0|1 preceded-by-newline> \\t
<JSON text>`. A token stream, not "whitespace collapsed", because collapsing
can't tell `SELECT a/*c*/b` (would fuse into identifier `ab`) from
`SELECT a /*c*/ b`. The newline flag guards Postgres string continuation:
two string constants separated by whitespace containing a newline are ONE
constant, so losing that newline changes the value.

normalize() RAISES (file skipped, unstripped) on: any unterminated literal
or COPY block; `standard_conforming_strings` OFF (changes backslash lexing);
any CR or exotic line separator; and -- not fastidiousness -- any `{{`, `{%`
or `{#` outside a literal, since a dbt/Jinja template mixed with real SQL can
have `--` as template text inside `{# ... #}`, which the normal form can't
see moving.

MySQL DANGER: `#` line comments are not recognised, and `#` is a valid
Postgres operator character, so `# note /*` really opens a Postgres block
comment and everything to the next `*/` gets deleted as "a comment" with
the normal form agreeing on both sides. Correct for Postgres, corrupting
for MySQL -- do not point this module at a MySQL file.
"""

from __future__ import annotations

import bisect
import json
import re
from functools import lru_cache

EXTS = ('.sql',)

# Directives, not prose. Removing any of these changes what a migration runner,
# a query-code generator or a linter does with the file.
#
# Migration-tool directives are listed even where migrations are plain DDL and
# never use them -- they cost nothing, and a stripper that silently eats
# `-- +goose Up` leaves no trace of what it broke. The pg_dump section header
# is common in practice: those files are regenerated by `pg_dump`, so stripping
# their headers buys nothing but permanent diff noise against the next dump --
# the same argument as `@generated`.
_KEEP_ALTERNATIVES = (
    r"--\s*no-transaction\b",                       # sqlx: run outside a transaction
    r"--\s*name\s*:\s*[A-Za-z_][\w-]*\s*(?::|$)",   # sqlc / yesql query name
    r"--\s*:\s*name\b",                             # HugSQL
    r"--\s*migrate\s*:\s*(?:up|down)\b",            # dbmate
    r"--\s*\+goose\b",                              # goose
    r"--\s*\+micrate\b",                            # micrate
    r"--\s*\+migrate\b",                            # sql-migrate
    r"--\s*atlas\s*:",                              # atlas: txmode / nolint / delimiter
    r"--\s*(?:liquibase|changeset|rollback|precondition)",
    r"--\s*(?:sqlfluff|noqa)\b",                    # sqlfluff lint control
    r"--\s*Name\s*:.*;\s*Type\s*:",                 # pg_dump object header
    r"--\s*(?:PostgreSQL database dump|Dumped (?:from|by)\b)",   # pg_dump preamble
    r"--\s*@?generated\b",
    r"(?:--|/\*)\s*SPDX-[A-Za-z-]+",
    r"/\*+\s*(?:@license|@preserve|@copyright)",
    # A template marker INSIDE a comment. The scanner refuses a file carrying
    # `{{` as SQL, but it never reads comment text, so `-- depends_on:
    # {{ ref('upstream') }}` -- dbt's documented way to declare an edge the
    # parser cannot infer -- reached the strip list as ordinary prose. Cutting
    # it deletes a dependency, and the normal form cannot object: it never saw
    # a token there either way. Keeping the comment is the whole fix; the rest
    # of such a file is still plain SQL and still gets swept.
    r"(?:--|/\*)[\s\S]*?\{[{%#]",
)
KEEP = re.compile("|".join("(?:%s)" % p for p in _KEEP_ALTERNATIVES), re.IGNORECASE)


class ParseError(ValueError):
    """The file does not parse; no normal form can be trusted for it."""


_WS = re.compile(r"[ \t\n]+")
# The high range runs to the top of the code space, not to U+FFFF: PostgreSQL
# admits any non-ASCII byte in an unquoted identifier, and stopping at the BMP
# would leave an astral character matching the branch guard but not the pattern.
_IDENT = re.compile(r"[A-Za-z_\u0080-\U0010ffff][A-Za-z0-9_$\u0080-\U0010ffff]*")
_NUMBER = re.compile(r"(?:\d|\.\d)[0-9A-Za-z_.]*")
_EXPONENT = re.compile(r"[+-]\d[\d_]*")
_OP_RUN = re.compile(r"[~!@#^&|`?+\-*/%<>=:]+")
_PARAM = re.compile(r"\$\d*")

# A dollar-quote delimiter: `$$` or `$tag$`, tag lexing like an unquoted identifier.
_DOLQ = re.compile(r"\$([A-Za-z_\u0080-\U0010ffff][A-Za-z0-9_\u0080-\U0010ffff]*)?\$")

# `COPY t (cols) FROM stdin;` -- the rest of the block is table data, not SQL.
# `[^;]*` and not `[^\n]*`: the statement is routinely wrapped (`COPY t (a, b)\n
# FROM stdin;`), and missing the wrapped form is not a lost strip but a silent
# data edit -- a `--` in a data row would be lexed as a comment and cut, and the
# normal form could not object because it agrees it was a comment. A COPY
# statement carries no `;` before its own terminator, so this cannot run past it.
_COPY_STDIN = re.compile(r"COPY\b[^;]*\bFROM\s+stdin\b[^;]*;[^\n]*\n", re.IGNORECASE)

# psql's client-side `\copy ... from stdin`: a meta-command, but the data block
# that follows it in the script is delimited exactly like COPY's.
_META_COPY_STDIN = re.compile(r"\\copy\b[^\n]*\bfrom\s+stdin\b", re.IGNORECASE)

# Backslashes inside ordinary strings become escapes when this is off, so the
# `''`-only rule below would mis-delimit. Every PostgreSQL since 9.1 defaults on.
_SCS_OFF = re.compile(
    r"standard_conforming_strings\s*(?:=|\bTO\b)\s*'?(?:off|false|0)'?", re.IGNORECASE)

# Characters str.splitlines() treats as line breaks but '\n' splitting does not.
# Their presence would desynchronise our line numbers from the driver's.
_ODD_BREAK = re.compile("[\r\v\f\x1c\x1d\x1e\x85\u2028\u2029]")


def _line_starts(src: str) -> list[int]:
    starts = [0]
    i = src.find("\n")
    while i != -1:
        starts.append(i + 1)
        i = src.find("\n", i + 1)
    return starts


def _row(starts: list[int], off: int) -> int:
    """1-based line number of a character offset."""
    return bisect.bisect_right(starts, off)


def _end_quoted(src: str, j: int, quote: str, backslash: bool, what: str,
                starts: list[int], opened: int) -> int:
    """Offset just past the closing `quote`. `quote+quote` is an embedded one."""
    n = len(src)
    while j < n:
        c = src[j]
        if backslash and c == "\\":
            j += 2
            continue
        if c == quote:
            if j + 1 < n and src[j + 1] == quote:
                j += 2
                continue
            return j + 1
        j += 1
    raise ParseError("unterminated %s opened at line %d" % (what, _row(starts, opened)))


def _end_number(src: str, i: int) -> int:
    m = _NUMBER.match(src, i)
    j = m.end()
    if src[j - 1] in "eE":
        e = _EXPONENT.match(src, j)
        if e:
            return e.end()
    return j


@lru_cache(maxsize=4)
def _scan(src: str) -> tuple[tuple, frozenset, str]:
    """Single pass yielding (comments, protected lines, token stream).

    One pass so a comment and the normal form can never be based on different
    ideas of where the literals are.
    """
    odd = _ODD_BREAK.search(src)
    if odd:
        raise ParseError(
            "carriage return or exotic line separator %r at offset %d: this file's "
            "line model would not match the driver's" % (odd.group(0), odd.start()))
    off = _SCS_OFF.search(src)
    if off:
        raise ParseError(
            "standard_conforming_strings is turned off (%r): backslash escaping in "
            "ordinary strings cannot be lexed by the `''`-only rule" % off.group(0))

    starts = _line_starts(src)
    n = len(src)
    found: list[tuple[int, int, int, str]] = []
    protected: set[int] = set()
    ws_lines: set[int] = set()
    records: list[str] = []
    state = {"prev_end": 0, "first": True, "stmt_start": True}

    def add_comment(s: int, e: int) -> None:
        # Withhold a comment whose removal would push two non-blank characters
        # together. `1-/*c*/-2` is the case that matters: cut it and the hyphens
        # become a comment marker, so a "comment removal" silently eats the rest
        # of the line. `a/*c*/b` -> `ab` and `a:/*c*/:b` -> `a::b` fuse likewise.
        # The test is blunt on purpose -- it also costs the harmless
        # `SELECT 1/*c*/;` its strip -- because an unstripped comment costs a
        # line and a fused one costs the statement. A `--` comment always ends at
        # a newline, so this only ever fires on `/* */`.
        if (s > 0 and src[s - 1] not in " \t\n"
                and e < n and src[e] not in " \t\n"):
            return
        first_line = _row(starts, s)
        last_line = _row(starts, e - 1)
        found.append((first_line, s - starts[first_line - 1],
                      e - starts[last_line - 1], src[s:e]))

    def emit(kind: str, s: int, e: int) -> None:
        nl = "0" if state["first"] else (
            "1" if src.find("\n", state["prev_end"], s) >= 0 else "0")
        state["first"] = False
        state["prev_end"] = e
        state["stmt_start"] = kind in ("meta", "copy") or (
            kind == "punct" and src[s:e] == ";")
        records.append("%s\t%s\t%s" % (kind, nl, json.dumps(src[s:e])))
        if src.find("\n", s, e - 1) >= 0:
            protected.update(range(_row(starts, s) + 1, _row(starts, e - 1) + 1))
        # Lines this token ends in trailing whitespace: that whitespace is
        # literal content, and the driver rstrips every line it edits. See the
        # filter below `while` -- a comment on such a line cannot be offered.
        p = src.find("\n", s, e)
        while p != -1:
            if p > s and src[p - 1] in " \t":
                ws_lines.add(_row(starts, p))
            p = src.find("\n", p + 1, e)

    def at_line_start(i: int) -> bool:
        return not src[starts[_row(starts, i) - 1]:i].strip()

    i = 0
    while i < n:
        c = src[i]

        if c in " \t\n":
            i = _WS.match(src, i).end()
            continue

        if c == "-" and src.startswith("--", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            add_comment(i, j)
            i = j
            continue

        if c == "/" and src.startswith("/*", i):
            depth, j = 1, i + 2
            while j < n and depth:
                two = src[j:j + 2]
                if two == "/*":
                    depth += 1
                    j += 2
                elif two == "*/":
                    depth -= 1
                    j += 2
                else:
                    j += 1
            if depth:
                raise ParseError("unterminated /* block comment opened at line %d"
                                 % _row(starts, i))
            add_comment(i, j)
            i = j
            continue

        if c == "'":
            j = _end_quoted(src, i + 1, "'", False, "string literal", starts, i)
            emit("str", i, j)
            i = j
            continue

        if c == '"':
            j = _end_quoted(src, i + 1, '"', False, "quoted identifier", starts, i)
            emit("qid", i, j)
            i = j
            continue

        if c == "$":
            m = _DOLQ.match(src, i)
            if m:
                tag = m.group(0)
                k = src.find(tag, m.end())
                if k < 0:
                    raise ParseError("unterminated %s dollar quote opened at line %d"
                                     % (tag, _row(starts, i)))
                j = k + len(tag)
                emit("dolq", i, j)
                i = j
                continue
            j = _PARAM.match(src, i).end()
            emit("param", i, j)
            i = j
            continue

        if c.isalpha() or c == "_" or ord(c) >= 0x80:
            if (c in "Cc") and (at_line_start(i) or state["stmt_start"]):
                m = _COPY_STDIN.match(src, i)
                if m:
                    j = _end_copy_block(src, m.end(), starts, i)
                    emit("copy", i, j)
                    i = j
                    continue
            j = _IDENT.match(src, i).end()
            if src[i:j] in ("E", "e") and j < n and src[j] == "'":
                j = _end_quoted(src, j + 1, "'", True, "E'' string", starts, i)
                emit("str", i, j)
            else:
                emit("ident", i, j)
            i = j
            continue

        if c.isdigit() or (c == "." and i + 1 < n and src[i + 1].isdigit()):
            j = _end_number(src, i)
            emit("num", i, j)
            i = j
            continue

        if c == "{" and src[i + 1:i + 2] in ("{", "%", "#"):
            raise ParseError(
                "template markers (%r at line %d): this is a dbt/Jinja model, not SQL. "
                "A `--` inside `{%s ... %s}` is template text, and cutting it would eat "
                "the closing delimiter -- a corruption this module's own normal form "
                "could not see" % (src[i:i + 2], _row(starts, i), "#", "#"))

        if c == "\\" and at_line_start(i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            if j < n and _META_COPY_STDIN.match(src, i):
                # `\copy ... from stdin` is fed by the script itself: the block
                # from the next line to `\.` is table data. One token from the
                # meta-command through the terminator, so its blank rows are
                # protected the same way COPY's are.
                emit("copy", i, _end_copy_block(src, j + 1, starts, i))
            else:
                emit("meta", i, j)
            i = state["prev_end"]
            continue

        if c in "~!@#^&|`?+-*/%<>=:":
            j = _OP_RUN.match(src, i).end()
            k = i + 1
            while k < j and src[k:k + 2] not in ("--", "/*"):
                k += 1
            emit("op", i, k)
            i = k
            continue

        emit("punct", i, i + 1)
        i += 1

    # The driver rstrips every line it edits. When the line a comment ends on
    # runs on into a multi-line literal, that trailing whitespace is literal
    # content -- `/*c*/ SELECT $$abc   ` + newline -- and rstripping it rewrites
    # the string. The gate catches it (the dollar-quoted token moves) and the
    # file is reverted, but a revert is a module bug by the driver's own rule,
    # so the comment is withheld instead, exactly as a fusing one is.
    if ws_lines:
        found = [f for f in found if f[0] + f[3].count("\n") not in ws_lines]

    return tuple(found), frozenset(protected), "\n".join(records)


def _end_copy_block(src: str, k: int, starts: list[int], opened: int) -> int:
    """Offset just past the `\\.` line closing a COPY ... FROM stdin data block."""
    n = len(src)
    while True:
        e = src.find("\n", k)
        if src[k:n if e < 0 else e] == "\\.":
            return n if e < 0 else e + 1
        if e < 0:
            raise ParseError("unterminated COPY ... FROM stdin block opened at line %d"
                             % _row(starts, opened))
        k = e + 1


def comments(src: str) -> list[tuple[int, int, int, str]]:
    """Every STRIPPABLE comment, in source order.

    Fusing comments are withheld -- see `_scan`.
    """
    return list(_scan(src)[0])


def protected_lines(src: str) -> set[int]:
    """Lines whose blankness is literal content, not formatting.

    A blank line inside a `$$ ... $$` function body is part of the source text
    PostgreSQL stores and hands to the PL handler; the same goes for a blank line
    in a multi-line string, in a quoted identifier, and in a COPY data block,
    where it is a row. Collapsing any of them rewrites data, not layout.
    """
    return set(_scan(src)[1])


def normalize(path: str) -> str:
    """Comment-free normal form of `path`; raises ParseError if it does not parse.

    No fallback: a file we cannot prove is a file we do not strip.
    """
    with open(path, encoding="utf-8", newline="") as fh:
        src = fh.read()
    return _scan(src)[2]
