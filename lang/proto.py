"""Protocol Buffers (.proto) language module (protoc C++ comment style).

    //  ... EOL      line comment      /* ... */   block comment (no nesting)
    "..."  '...'     string, may NOT cross a line
    #                NOT a comment -- protoc's tokenizer is CPP-style only, `#`
                     is a syntax error

READ BEFORE STRIPPING A .proto: unlike every other language here, a comment is
NOT inert. protoc records comments in SourceCodeInfo, and generators (prost,
ts-proto, protoc-gen-go, protoc-gen-doc, grpc) emit a leading/trailing comment
as a `///` doc comment on the generated type -- so stripping one changes the
generated API surface even though the wire format doesn't move. KEEP only sees
comment TEXT, not position, so it can protect doc-comment syntax (`///` `//!`
`/**`), generator tags (`@deprecated`), tool directives (`protolint:disable`,
`buf:lint:ignore`), legal headers, and the two wire-relevant markers
(commented-out `reserved`, `next id:`/`NEXT_ID:`) -- but an ordinary `//`
comment above/beside a field IS reported strippable and WILL be taken by
`strip --all`; on a generated-code repo that is a real output change, so
prefer `comments-list` + targeted `strip`. `--collapse-blanks` can re-attach a
surviving leading-detached comment to the wrong declaration -- the gate can't
see this, since the normal form has no comments in it.

normal form: a token stream, `<kind>\\t<JSON text>` per record, built by this
module's own scanner -- so the inventory and the proof can't disagree.
"""

from __future__ import annotations

import bisect
import json
import re
from functools import lru_cache

EXTS = ('.proto',)

# Doc-comment SYNTAX: the author wrote these to be emitted, so they are output
# even before you read them. `///` and `//!` are Rust/C# doc comments, `/**` and
# `/*!` the JSDoc form that ts-proto and protoc-gen-doc pick up.
_DOC_OPENERS = (
    r"/{3,}",
    r"//!",
    r"/\*[*!]",
)

# Directives and structured markers, matched ANYWHERE in the comment text (a tag
# in a `/** ... */` block sits on its own line, not at the opener).
_DIRECTIVES = (
    # doc tags a generator or docs pipeline consumes
    r"@(?:deprecated|experimental|internal|alpha|beta|public|private|remarks|"
    r"param|returns?|see|since|example|link|default|throws|readonly|nodoc|"
    r"summary|template|typedef|category|group|packageDocumentation)\b",
    r"@(?:license|preserve|copyright|generated)\b",
    r"@gotags\s*:",                          # protoc-go-inject-tag
    # linters and formatters
    r"\bprotolint\s*:\s*(?:disable|enable)",
    r"\bbuf\s*:\s*lint\s*:\s*ignore",
    r"\bapi-linter\s*:",
    r"\bno[- ]?lint\b",
    r"\bclang-format\s+(?:on|off)\b",
    r"(?://+|\*)\s*\+(?:optional|required|patchStrategy|patchMergeKey|listType|"
    r"genclient|kubebuilder:)",              # gengo/kubebuilder markers
    # legal and provenance
    r"SPDX-[A-Za-z-]+",
    r"\bcopyright\b|©|\(c\)\s*\d{4}",
    r"\blicen[cs]ed under\b|\ball rights reserved\b",
    r"\bgenerated by\b|DO ?NOT ?EDIT|AUTO-?GENERATED",
    # editor modelines
    r"\bvi(?:m)?\s*:\s*(?:set\s+)?\w+|-\*-",
    # protobuf-specific: losing either of these invites a field-number reuse,
    # which silently corrupts the wire format for every already-deployed reader.
    r"\breserved\b",
    # `Next id: 15`, `NEXT_ID: 15`, `next free tag: 9`. The underscore spelling
    # is the common one in Google-style protos, so the separator is [_\s]+, not
    # \s+ -- `\bnext\s+` alone silently loses every NEXT_ID marker, which is the
    # exact record that says a field number must never be reused.
    r"\bnext[_\s]+(?:free[_\s]+|available[_\s]+)?(?:id|tag|field)\b",
    r"\bdeprecated\b",
)

# The driver applies this with `.match`, i.e. anchored at offset 0. The first
# branch is that anchor (an opener is only an opener at the start); the second
# is a lazy any-prefix, which turns the directive alternatives into a search.
KEEP = re.compile(
    r"^(?:%s)|[\s\S]*?(?:%s)" % ("|".join(_DOC_OPENERS), "|".join(_DIRECTIVES)),
    re.IGNORECASE | re.MULTILINE,
)

# Identifier / number / qualified-name run. Kept as ONE token class so that a
# strip which fuses two of them (`Foo/*c*/Bar` -> `FooBar`) moves the normal
# form and is reverted. The cost is a false revert on the reverse case
# (`foo/*c*/.bar`), which nobody writes and which costs a strip, not a file.
_WORD = re.compile(r"[A-Za-z0-9_.]+")

_WS = " \t\r\n"

# Characters `str.splitlines()` breaks on that counting "\n" does not see.
# They matter because the driver indexes `src.splitlines(keepends=True)` and
# derives a span's last line as `line + text.count("\n")`: on a source holding
# any of these, the driver's line model and this module's disagree, and excise()
# then cuts the wrong columns of the wrong line. Observed: a U+2028 inside a
# string literal was silently deleted from the literal, and a "\f" between
# declarations turned a requested strip into a silent no-op reported as
# "unchanged". The mismatch cannot be repaired from inside this module, because
# the driver's own count is "\n"-only -- so such a file is declared unlexable
# and skipped, the same trade-off as an unterminated comment. protoc accepts
# them (as whitespace, or as bytes inside a string), but refusing to strip is
# cheaper than a mis-cut line.
_ALIEN_BREAK = re.compile("[\v\f\x1c\x1d\x1e\x85\u2028\u2029]|\r(?!\n)")


class ParseError(ValueError):
    """The file does not lex; no normal form can be trusted for it."""


def _line_starts(src: str) -> list[int]:
    starts = [0]
    i = src.find('\n')
    while i != -1:
        starts.append(i + 1)
        i = src.find('\n', i + 1)
    return starts


def _locate(starts: list[int], off: int) -> tuple[int, int]:
    row = bisect.bisect_right(starts, off) - 1
    return row + 1, off - starts[row]


@lru_cache(maxsize=8)
def _lex(src: str) -> tuple[tuple, frozenset, str]:
    """(comments, protected lines, token stream) from a single scan.

    Raises ParseError on anything this scanner cannot account for -- an
    unterminated block comment, a string literal that runs to EOF or across a
    line (which protoc rejects too: "String literals cannot cross line
    boundaries"), or a character the driver's `splitlines` would count as a line
    break and this module's newline arithmetic would not (see _ALIEN_BREAK).
    A file we cannot lex is a file we do not strip.
    """
    alien = _ALIEN_BREAK.search(src)
    if alien:
        raise ParseError(
            'line break U+%04X at line %d that str.splitlines() honours but a '
            'newline count does not; line numbers would not survive the round trip'
            % (ord(alien.group()), src.count('\n', 0, alien.start()) + 1))

    starts = _line_starts(src)
    found: list[tuple[int, int, int, str]] = []
    protected: set[int] = set()
    tokens: list[str] = []
    i, n = 0, len(src)

    def record(a: int, b: int) -> None:
        line, col = _locate(starts, a)
        found.append((line, col, _locate(starts, b)[1], src[a:b]))

    while i < n:
        c = src[i]

        if c in _WS:
            i += 1
            continue

        if c == '/' and i + 1 < n and src[i + 1] == '/':
            j = src.find('\n', i)
            if j == -1:
                j = n
            elif j > i and src[j - 1] == '\r':
                j -= 1          # leave the CR to the whitespace branch
            record(i, j)
            i = j
            continue

        if c == '/' and i + 1 < n and src[i + 1] == '*':
            j = src.find('*/', i + 2)
            if j == -1:
                raise ParseError('unterminated block comment opened at line %d'
                                 % _locate(starts, i)[0])
            j += 2
            record(i, j)
            first, last = _locate(starts, i)[0], _locate(starts, j - 1)[0]
            protected.update(range(first + 1, last))
            i = j
            continue

        if c == '"' or c == "'":
            j = i + 1
            while True:
                if j >= n:
                    raise ParseError('unterminated string literal opened at line %d'
                                     % _locate(starts, i)[0])
                d = src[j]
                if d == '\n':
                    raise ParseError('string literal crosses a line boundary at line %d'
                                     % _locate(starts, i)[0])
                if d == '\\':
                    if j + 1 >= n or src[j + 1] == '\n':
                        raise ParseError('string literal crosses a line boundary at line %d'
                                         % _locate(starts, i)[0])
                    j += 2
                    continue
                if d == c:
                    j += 1
                    break
                j += 1
            tokens.append('S\t' + json.dumps(src[i:j]))
            i = j
            continue

        m = _WORD.match(src, i)
        if m:
            tokens.append('W\t' + json.dumps(m.group()))
            i = m.end()
            continue

        tokens.append('P\t' + json.dumps(c))
        i += 1

    return tuple(found), frozenset(protected), '\n'.join(tokens)


def comments(src: str) -> list[tuple[int, int, int, str]]:
    """Every comment in `src`, in source order; raises ParseError if it does not lex.

    The driver swallows that raise and treats the file as comment-free, so an
    unlexable .proto is silently absent from `list` and never stripped. Erring
    that way is the point: the alternative is reporting spans a broken scan
    cannot vouch for.
    """
    return list(_lex(src)[0])


def protected_lines(src: str) -> set[int]:
    """Lines whose blankness is content, not formatting.

    A .proto string literal cannot cross a line, so no blank line is ever inside
    one. What can be lost instead is a blank line INSIDE a retained block
    comment: comments are absent from the normal form by construction, so the
    gate would never notice `--collapse-blanks` rewriting a license header's
    paragraph breaks. Those interior lines are the whole set.
    """
    return set(_lex(src)[1])


def normalize(path: str) -> str:
    """Comment-free normal form; raises ParseError if `path` does not lex.

    Two files with the same normal form have the same token stream -- same
    literals, same identifiers, same punctuation, same order -- and differ only
    in comments and in whitespace that separates nothing. That is exactly the
    claim a comment strip has to prove. No fallback: a file we cannot prove is a
    file we do not strip.
    """
    with open(path, encoding='utf-8') as fh:
        src = fh.read()
    return _lex(src)[2]
